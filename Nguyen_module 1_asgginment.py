#Queue Implementation

class queue:
  def __init__(self):
    self.data = []
  def enqueue(self,value):
    self.data.append(value)
  def dequeue(self):
    return self.data.pop(0)
  def front(self):
    return self.data[0]

# simulates a waiting line
customer_line = queue()

customer_line.enqueue("A")
customer_line.enqueue("B")
customer_line.enqueue("C")

print(customer_line.data)

# customers arriving
print("Waiting line:", customer_line.data)
print("Next customer:", customer_line.front())

# served in order
print("Next customer:", customer_line.dequeue())
print("Waiting line:", customer_line.data)